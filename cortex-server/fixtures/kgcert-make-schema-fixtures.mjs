// KG-CERT — generates the schema fixtures of the intermediate KG versions (test assets only;
// run by hand: `node fixtures/kgcert-make-schema-fixtures.mjs`). Temporary in-memory databases.
//
//   kgcert-schema-2.2.0.sql  EXACT: the current schema minus kg_relationship_provenance (the only
//                            object migration 008 adds), schema_version 2.2.0.
//   kgcert-schema-2.1.0.sql  RECONSTRUCTED: the same tables / indexes (migration 007 changed FTS
//                            only) with the KG-3/KG-4 FTS objects copied verbatim from the captured
//                            kg3-schema-2.0.0.sql (no kg_evidence_fts, triggers keyed on the id
//                            column), schema_version 2.1.0. The KG-4 source code itself was not kept.
import fs from 'node:fs';
import { KnowledgeGraphStore } from '../src/lib/kg-store.js';

const here = new URL('.', import.meta.url);
const store = await KnowledgeGraphStore.createTempStore();
const db = store.db;
db.exec('DROP TABLE kg_relationship_provenance');
const objects = db.prepare("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY rowid").all();
const ftsShadow = (name) => /^kg_\w+_fts_(data|idx|content|docsize|config)$/.test(name);
const isFts = (o) => /_fts$/.test(o.name) || /_fts_(ai|au|ad)$/.test(o.name) || ftsShadow(o.name);
const base = objects.filter(o => !isFts(o) && o.name !== 'sqlite_sequence').map(o => `${o.sql};`);
const fts22 = objects.filter(o => isFts(o) && !ftsShadow(o.name)).map(o => `${o.sql};`);
store.close();

const head = (v, text) => `-- KG schema ${v} — ${text}\n-- Generated by fixtures/kgcert-make-schema-fixtures.mjs (KG-CERT, 2026-10-12). Test fixture only.\n`;
const version = (v) => `INSERT INTO kg_metadata (key, value, updated_at) VALUES ('schema_version', '${v}', '2026-10-12T00:00:00.000Z');\n`;
fs.writeFileSync(new URL('kgcert-schema-2.2.0.sql', here),
  head('2.2.0', 'EXACT (current schema minus kg_relationship_provenance, the only object of migration 008).') + [...base, ...fts22].join('\n') + '\n' + version('2.2.0'));

const v200 = fs.readFileSync(new URL('kg3-schema-2.0.0.sql', here), 'utf8');
const ftsStart = v200.indexOf('CREATE VIRTUAL TABLE kg_entities_fts');
const ftsEnd = v200.indexOf("INSERT INTO kg_metadata");
const fts20 = v200.slice(ftsStart, ftsEnd).trim();
fs.writeFileSync(new URL('kgcert-schema-2.1.0.sql', here),
  head('2.1.0', 'RECONSTRUCTED: 2.2.0 tables / indexes (007 changed FTS only) + the KG-3/KG-4 FTS objects of kg3-schema-2.0.0.sql.') + base.join('\n') + '\n' + fts20 + '\n' + version('2.1.0'));
console.log(`base objects ${base.length}, 2.2.0 FTS objects ${fts22.length}, 2.1.0 FTS block ${fts20.split('\n').length} lines`);
